    const LEVELS = [LEVEL_1, LEVEL_2, LEVEL_3, LEVEL_4, LEVEL_5, LEVEL_6];

    /**
     * Получить уровень по индексу (0-5)
     */
    function getLevel(index) {
        return LEVELS[index] || null;
    }

    /**
     * Получить уровень по id ('level-1' ... 'level-6')
     */
    function getLevelById(id) {
        return LEVELS.find(l => l.id === id) || null;
    }

    /**
     * Получить все уровни
     */
    function getAllLevels() {
        return LEVELS;
    }

    /**
     * Получить урок конкретного уровня по индексу
     */
    function getLesson(levelIndex, lessonNumber) {
        const level = getLevel(levelIndex);
        if (!level) return null;
        return level.lessons[lessonNumber - 1] || null;
    }

    /**
     * Получить количество уроков в уровне
     */
    function getLessonCount(levelIndex) {
        const level = getLevel(levelIndex);
        return level ? level.lessons.length : 0;
    }

    /**
     * Получить tags уровня (для фильтрации сценариев)
     */
    function getLevelTags(levelIndex) {
        const level = getLevel(levelIndex);
        return level ? (level.tags || []) : [];
    }

